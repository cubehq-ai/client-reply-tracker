import { useEffect, useMemo, useRef, useState } from 'react';
import { splitQuoted } from './quoted';
import { prepareHtml } from './mailHtml';
import type { ThreadView } from './api';

type ThreadMessage = ThreadView['messages'][number];

/** Taller than this and the message gets an expander instead. */
const CLAMP_HEIGHT = 440;

/**
 * One message in a thread. Collapsed it is a single summary line, the way any
 * mail client shows history; expanded it shows what was written, with quoted
 * history behind its own toggle.
 */
export function Message({ message, open, onToggle, onReply, onReplyAll, earlierMessages }: {
  message: ThreadMessage;
  open: boolean;
  onToggle: () => void;
  onReply: () => void;
  onReplyAll: () => void;
  /** Opening text of the messages before this one, for quote detection. */
  earlierMessages: string[];
}) {
  const [showQuoted, setShowQuoted] = useState(false);
  const [showImages, setShowImages] = useState(false);
  const [expanded, setExpanded] = useState(false);
  const [clamped, setClamped] = useState(false);
  const bodyRef = useRef<HTMLDivElement | null>(null);
  const when = new Date(message.date);

  // Render the HTML part when there is one, the way a mail client does. The
  // text/plain alternative is generated by the sender's client and is full of
  // [cid:...] references and alt text for signature icons.
  const inlineImages = useMemo(() => {
    const map = new Map<string, string>();
    for (const a of message.attachments ?? []) {
      if (a.contentId) map.set(a.contentId, `/api/attachments/${a.id}?inline=true`);
    }
    return map;
  }, [message.attachments]);

  const html = useMemo(
    () => (message.bodyHtml ? prepareHtml(message.bodyHtml, { showImages, inlineImages, earlierMessages }) : null),
    [message.bodyHtml, showImages, inlineImages, earlierMessages],
  );

  const files = (message.attachments ?? []).filter((a) => !a.isInline);
  const text = html ? null : splitQuoted(message.body || message.snippet || '');

  // Quote detection cannot cover every mail client, and a signature table can
  // be taller than the message. Clamp anything long and let the reader open
  // it, which is what a mail client does with trimmed content.
  useEffect(() => {
    const el = bodyRef.current;
    if (!el) return;
    setClamped(el.scrollHeight > CLAMP_HEIGHT + 80);
  }, [message.id, showImages, showQuoted, html]);
  const visible = html ? html.visible : text!.visible;
  const quoted = html ? html.quoted : text!.quoted;

  if (!open) {
    return (
      <button className="msg-collapsed" onClick={onToggle} title="Expand">
        <span className="msg-collapsed-from">{message.from}</span>
        <span className="msg-collapsed-preview">{preview(message, 140)}</span>
        <span className="msg-collapsed-date">{when.toLocaleDateString(undefined, { month: 'short', day: 'numeric' })}</span>
      </button>
    );
  }

  const to = message.to.filter(Boolean);
  const cc = message.cc.filter(Boolean);
  const bcc = (message.bcc ?? []).filter(Boolean);
  const replyAllCount = to.length + cc.length;

  return (
    <div className={`msg ${message.direction === 'out' ? 'out' : ''}`}>
      {/* The whole header toggles, mirroring how a collapsed row expands.
          The action buttons stop the event so they still do their own job. */}
      <div className="msg-head msg-head-toggle" onClick={onToggle} title="Collapse">
        <span className="msg-head-who">
          <div>
            <strong>{message.from}</strong>
            {message.isDraft && <span className="tag" style={{ marginLeft: 6 }}>draft</span>}
            {message.filterReason && <span className="tag" style={{ marginLeft: 6 }}>{message.filterReason}</span>}
          </div>
          {to.length > 0 && <div className="addr-line"><span className="addr-label">To</span>{to.join(', ')}</div>}
          {cc.length > 0 && <div className="addr-line"><span className="addr-label">Cc</span>{cc.join(', ')}</div>}
          {bcc.length > 0 && <div className="addr-line"><span className="addr-label">Bcc</span>{bcc.join(', ')}</div>}
        </span>
        <span className="msg-head-actions" onClick={(e) => e.stopPropagation()}>
          <span className="muted">{when.toLocaleString()}</span>
          <button className="btn small" onClick={onReply} title="Reply to this message">Reply</button>
          {replyAllCount > 1 && (
            <button className="btn small" onClick={onReplyAll} title="Reply to everyone on this message">Reply all</button>
          )}
          <button className="btn small" onClick={onToggle} title="Collapse">−</button>
        </span>
      </div>

      {html ? (
        <>
          {html.blockedImages > 0 && (
            <div className="images-blocked">
              {html.blockedImages} image{html.blockedImages === 1 ? '' : 's'} not shown
              <button className="btn small" onClick={() => setShowImages(true)}>Show images</button>
            </div>
          )}
          <div
            ref={bodyRef}
            className={`msg-body msg-html ${clamped && !expanded ? 'clamped' : ''}`}
            dangerouslySetInnerHTML={{ __html: visible }}
          />
          {clamped && (
            <button className="quoted-toggle" onClick={() => setExpanded((v) => !v)}>
              {expanded ? 'Show less' : '••• Show full message'}
            </button>
          )}
        </>
      ) : (
        <>
          <div ref={bodyRef} className={`msg-body ${clamped && !expanded ? 'clamped' : ''}`}>
            {visible || <span className="muted">(no new text in this message)</span>}
          </div>
          {clamped && (
            <button className="quoted-toggle" onClick={() => setExpanded((v) => !v)}>
              {expanded ? 'Show less' : '••• Show full message'}
            </button>
          )}
        </>
      )}

      {files.length > 0 && (
        <div className="attachments">
          {files.map((a) => (
            <a key={a.id} className="attachment" href={`/api/attachments/${a.id}`} download={a.filename}>
              <span className="attachment-name">{a.filename}</span>
              <span className="attachment-size">{formatSize(a.size)}</span>
            </a>
          ))}
        </div>
      )}

      {quoted && (
        <div className="msg-quoted">
          <button className="quoted-toggle" onClick={() => setShowQuoted((v) => !v)}>
            {showQuoted ? 'Hide quoted text' : '••• Show quoted text'}
          </button>
          {showQuoted && (html
            ? <div className="quoted-body msg-html" dangerouslySetInnerHTML={{ __html: quoted }} />
            : <pre className="quoted-body">{quoted}</pre>)}
        </div>
      )}
    </div>
  );
}

/** One line for a collapsed row, from whichever body the message has. */
function preview(message: ThreadMessage, max: number): string {
  if (message.snippet) return message.snippet.slice(0, max);
  const plain = (message.body ?? '').replace(/\s+/g, ' ').trim();
  return plain.slice(0, max);
}

function formatSize(bytes: number): string {
  if (!bytes) return '';
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
